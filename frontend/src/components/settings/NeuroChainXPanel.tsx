const buildUrl = (base: string, path: string) => {
  const cleaned = tidyUrl(base)
  if (!cleaned) return ''
  if (path.startsWith('http')) return path
  return `${cleaned}${path.startsWith('/') ? '' : '/'}${path}`
}

